"""Builds lisa_tokenizer.bin: a real 4096-entry BPE vocabulary for LISA's model.

Why: the model reads only the first 4096 entries of tokenizer.bin (the 32000-entry
Llama-2 tokenizer). In that file every single character ('e', 't', ' ', ...) sits
near the END, so the first 4096 entries contain none of them. Every character then
falls back to a byte token <0xNN>, and no merge can ever start: text costs one
token per byte, which makes the model ~3x slower and its 128-token context ~3x
shorter than it should be.

The new vocabulary keeps the llama2.c file format and the special/byte ids, so the
firmware's bpe_tokenizer.h and server/app/evolution/tokenizer.py read it unchanged:
    0..2      <unk> <s> </s>                 (as in tokenizer.bin)
    3..258    <0x00>..<0xFF> byte fallback    (as in tokenizer.bin)
    259..353  printable ASCII characters ' '..'~'
    354..4095 the highest-priority ASCII merges of tokenizer.bin, in their original
              order (BPE order: every merge's parts come before it), each kept only
              if it can actually be built from two earlier entries.

    python tools/build_lisa_tokenizer.py tokenizer.bin lisa_tokenizer.bin [edge/lisa_tokenizer_data.h]
"""
from __future__ import annotations

import struct
import sys
import zlib
from pathlib import Path

VOCAB = 4096


def read_llama2c(path: Path) -> tuple[int, list[tuple[float, bytes]]]:
    data = path.read_bytes()
    max_len = struct.unpack_from("<i", data, 0)[0]
    off, entries = 4, []
    while off + 8 <= len(data):
        score, n = struct.unpack_from("<fi", data, off)
        off += 8
        entries.append((score, data[off:off + n]))
        off += n
    return max_len, entries


def build(src: Path) -> list[tuple[float, bytes]]:
    _, entries = read_llama2c(src)
    scores = {tok: score for score, tok in entries}
    out = list(entries[:259])                                   # specials + byte fallbacks
    assert out[3][1] == b"<0x00>" and out[258][1] == b"<0xFF>", "unexpected tokenizer.bin layout"
    have = {tok for _, tok in out}
    for c in range(0x20, 0x7F):                                 # every printable ASCII character
        ch = bytes([c])
        out.append((scores.get(ch, 0.0), ch))
        have.add(ch)
    for score, tok in entries[259:]:
        if len(out) >= VOCAB:
            break
        if len(tok) < 2 or tok in have or not all(0x20 <= b < 0x7F for b in tok):
            continue
        # Reachable: some split into two tokens we already have (BPE builds tokens pairwise).
        if any(tok[:i] in have and tok[i:] in have for i in range(1, len(tok))):
            out.append((score, tok))
            have.add(tok)
    assert len(out) == VOCAB, f"only {len(out)} entries"
    return out


def serialize(entries: list[tuple[float, bytes]]) -> bytes:
    body = b"".join(struct.pack("<fi", s, len(t)) + t for s, t in entries)
    return struct.pack("<i", max(len(t) for _, t in entries)) + body


def c_header(data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return (
        "#pragma once\n"
        "// Generated by tools/build_lisa_tokenizer.py from lisa_tokenizer.bin. Do not edit.\n"
        "// LISA's 4096-entry BPE vocabulary (llama2.c format), built into the firmware so the\n"
        "// tokenizer can never drift from the one the server trains with.\n"
        "#include <stddef.h>\n#include <stdint.h>\n\n"
        f"static const uint32_t kLisaTokenizerCrc32 = 0x{zlib.crc32(data):08x}u;\n"
        f"static const size_t kLisaTokenizerBytes = {len(data)};\n"
        "static const uint8_t kLisaTokenizer[] = {\n    " + ",\n    ".join(rows) + "\n};\n"
    )


def main() -> None:
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    data = serialize(build(src))
    dst.write_bytes(data)
    print(f"{dst}: {len(data)} bytes, crc32 {zlib.crc32(data):08x}")
    if len(sys.argv) > 3:
        Path(sys.argv[3]).write_text(c_header(data), encoding="utf-8", newline="\n")
        print(f"{sys.argv[3]}: C array written")


if __name__ == "__main__":
    main()
